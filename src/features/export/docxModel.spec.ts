import { describe, expect, it } from 'vitest';
import type { TranscriptDoc } from '../../domain/transcript';
import { makeDoc, withTranslation } from '../../testing/transcriptDoc';
import { buildDocModel, type DocModelOptions } from './docxModel';

const OPTS: DocModelOptions = {
  version: 'original',
  generatedAt: new Date('2026-10-14T08:30:00Z'),
  appVersion: '1.2.3',
  timeZone: 'UTC',
};

const metaOf = (doc: TranscriptDoc, opts: Partial<DocModelOptions> = {}) =>
  Object.fromEntries(buildDocModel(doc, { ...OPTS, ...opts }).meta.map((m) => [m.label, m.value]));

describe('buildDocModel', () => {
  it('builds the original version of the fixture doc', () => {
    expect(buildDocModel(makeDoc(), OPTS)).toMatchInlineSnapshot(`
      {
        "meta": [
          {
            "label": "Source file",
            "value": "interview.mp3",
          },
          {
            "label": "Duration",
            "value": "00:00:16",
          },
          {
            "label": "Transcribed",
            "value": "13 Oct 2026, 12:05",
          },
          {
            "label": "Language",
            "value": "German (detected)",
          },
          {
            "label": "Speakers",
            "value": "Speaker 1, Speaker 2",
          },
          {
            "label": "Transcription",
            "value": "ElevenLabs scribe_v2",
          },
          {
            "label": "Exported",
            "value": "14 Oct 2026, 08:30",
          },
        ],
        "paragraphs": [
          {
            "speaker": "Speaker 1",
            "text": "Guten Tag und willkommen zu unserem Gespräch.",
            "timestamp": "00:00:00",
          },
          {
            "speaker": "Speaker 2",
            "text": "Danke, ich freue mich sehr.",
            "timestamp": "00:00:03",
          },
          {
            "speaker": "Speaker 1",
            "text": "Wie lange arbeiten Sie schon an dem Projekt?",
            "timestamp": "00:00:06",
          },
          {
            "speaker": "Speaker 2",
            "text": "Seit ungefähr zwei Jahren, gemeinsam mit einem kleinen Team.",
            "timestamp": "00:00:09",
          },
          {
            "speaker": "Speaker 1",
            "text": "Was war bisher die größte Herausforderung?",
            "timestamp": "00:00:13",
          },
        ],
        "properties": {
          "description": "Generated by DeScribe v1.2.3",
          "title": "Transcript – interview",
        },
        "title": "Transcript – interview",
      }
    `);
  });

  it('builds the English version from the translation', () => {
    expect(buildDocModel(withTranslation(makeDoc()), { ...OPTS, version: 'en' }))
      .toMatchInlineSnapshot(`
        {
          "meta": [
            {
              "label": "Source file",
              "value": "interview.mp3",
            },
            {
              "label": "Duration",
              "value": "00:00:16",
            },
            {
              "label": "Transcribed",
              "value": "13 Oct 2026, 12:05",
            },
            {
              "label": "Language",
              "value": "English (translated from German with Claude, claude-opus-5-5)",
            },
            {
              "label": "Speakers",
              "value": "Speaker 1, Speaker 2",
            },
            {
              "label": "Transcription",
              "value": "ElevenLabs scribe_v2",
            },
            {
              "label": "Exported",
              "value": "14 Oct 2026, 08:30",
            },
          ],
          "paragraphs": [
            {
              "speaker": "Speaker 1",
              "text": "Good afternoon and welcome to our conversation.",
              "timestamp": "00:00:00",
            },
            {
              "speaker": "Speaker 2",
              "text": "Thank you, I'm very pleased to be here.",
              "timestamp": "00:00:03",
            },
            {
              "speaker": "Speaker 1",
              "text": "How long have you been working on the project?",
              "timestamp": "00:00:06",
            },
            {
              "speaker": "Speaker 2",
              "text": "For about two years, together with a small team.",
              "timestamp": "00:00:09",
            },
            {
              "speaker": "Speaker 1",
              "text": "What has been the biggest challenge so far?",
              "timestamp": "00:00:13",
            },
          ],
          "properties": {
            "description": "Generated by DeScribe v1.2.3",
            "title": "Transcript – interview",
          },
          "title": "Transcript – interview",
        }
      `);
  });

  it('lists the details in a fixed order', () => {
    const doc = makeDoc({ request: { ...makeDoc().request, keyterms: ['Oticon'] } });
    expect(buildDocModel(doc, OPTS).meta.map((m) => m.label)).toEqual([
      'Source file',
      'Duration',
      'Transcribed',
      'Language',
      'Speakers',
      'Transcription',
      'Exported',
    ]);
  });

  it('uses the current speaker names', () => {
    const doc = makeDoc();
    const renamed = {
      ...doc,
      speakers: doc.speakers.map((s, i) => (i === 0 ? { ...s, label: 'Interviewer' } : s)),
    };
    const model = buildDocModel(renamed, OPTS);
    expect(model.paragraphs.map((p) => p.speaker)).toEqual([
      'Interviewer',
      'Speaker 2',
      'Interviewer',
      'Speaker 2',
      'Interviewer',
    ]);
    expect(metaOf(renamed).Speakers).toBe('Interviewer, Speaker 2');
  });

  it('says "detected" only when the language was detected', () => {
    const doc = makeDoc();
    expect(metaOf(doc).Language).toBe('German (detected)');
    expect(metaOf({ ...doc, request: { ...doc.request, languageHint: 'de' } }).Language).toBe(
      'German',
    );
  });

  it('leaves the language out when it is not known', () => {
    const doc = makeDoc();
    const unknown = { ...doc, result: { ...doc.result, languageCode: '' } };
    expect(metaOf(unknown)).not.toHaveProperty('Language');
    expect(
      metaOf({ ...unknown, request: { ...unknown.request, languageHint: 'de' } }),
    ).not.toHaveProperty('Language');
    expect(metaOf(withTranslation(unknown), { version: 'en' }).Language).toBe(
      'English (translated with Claude, claude-opus-5-5)',
    );
  });

  it('names the translation provider and model', () => {
    const doc = withTranslation(makeDoc());
    expect(metaOf(doc, { version: 'en' }).Language).toBe(
      'English (translated from German with Claude, claude-opus-5-5)',
    );
    const gemini = {
      ...doc,
      translations: {
        en: { ...doc.translations.en!, provider: 'gemini' as const, model: 'gemini-3.8-flash' },
      },
    };
    expect(metaOf(gemini, { version: 'en' }).Language).toBe(
      'English (translated from German with Gemini, gemini-3.8-flash)',
    );
  });

  it('takes the duration from the result, then the probe, and leaves it out if neither is known', () => {
    const doc = makeDoc();
    const withDurations = (audio: number | null, probed: number | null) => ({
      ...doc,
      result: { ...doc.result, audioDurationSec: audio },
      source: { ...doc.source, durationSec: probed },
    });
    expect(metaOf(withDurations(3725.9, 10)).Duration).toBe('01:02:05');
    expect(metaOf(withDurations(null, 61)).Duration).toBe('00:01:01');
    expect(metaOf(withDurations(null, null))).not.toHaveProperty('Duration');
  });

  it('counts glossary terms', () => {
    const doc = makeDoc();
    const terms = (keyterms: string[]) => ({ ...doc, request: { ...doc.request, keyterms } });
    expect(metaOf(terms([])).Transcription).toBe('ElevenLabs scribe_v2');
    expect(metaOf(terms(['Oticon'])).Transcription).toBe(
      'ElevenLabs scribe_v2 · glossary of 1 term',
    );
    expect(metaOf(terms(['Oticon', 'Demant'])).Transcription).toBe(
      'ElevenLabs scribe_v2 · glossary of 2 terms',
    );
  });

  it('refuses an English export without a complete translation', () => {
    expect(() => buildDocModel(makeDoc(), { ...OPTS, version: 'en' })).toThrow(
      'translation incomplete',
    );
    const partial = withTranslation(makeDoc(), { t1: 'Hello.', t2: 'Thanks.' });
    expect(() => buildDocModel(partial, { ...OPTS, version: 'en' })).toThrow(
      'translation incomplete',
    );
  });

  it('exports the original even when a translation exists', () => {
    const model = buildDocModel(withTranslation(makeDoc()), OPTS);
    expect(model.paragraphs[0]?.text).toBe('Guten Tag und willkommen zu unserem Gespräch.');
  });
});

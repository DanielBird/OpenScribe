// What goes into the Word file (DECISIONS.md D9), as plain data. Pure: docxRender.ts turns it into a .docx.
import {
  formatDateTime,
  formatTimestamp,
  languageName,
  type LlmProviderId,
  type TranscriptDoc,
  type TranscriptVersion,
} from '../../domain/transcript';
import { fileBaseName } from './fileName';

export interface DocModel {
  title: string;
  meta: { label: string; value: string }[];
  paragraphs: { timestamp: string; speaker: string; text: string }[];
  properties: { title: string; description: string };
}

export interface DocModelOptions {
  version: TranscriptVersion;
  generatedAt: Date;
  appVersion: string;
  /** For tests. The app leaves it out, so dates show in the viewer's time zone. */
  timeZone?: string;
}

const PROVIDER_NAMES: Record<LlmProviderId, string> = { claude: 'Claude', gemini: 'Gemini' };
const TRANSCRIPTION_PROVIDER_NAMES: Record<TranscriptDoc['request']['provider'], string> = {
  elevenlabs: 'ElevenLabs',
};

/** Throws `Error('translation incomplete')` for `version: 'en'` unless every turn has a translation. */
export function buildDocModel(doc: TranscriptDoc, opts: DocModelOptions): DocModel {
  const { source, request, result } = doc;
  const formatDate = (iso: string) => formatDateTime(iso, { timeZone: opts.timeZone });
  const original = languageName(result.languageCode);

  const translation = opts.version === 'en' ? doc.translations.en : undefined;
  if (opts.version === 'en' && !translation) throw new Error('translation incomplete');

  const meta: DocModel['meta'] = [{ label: 'Source file', value: source.fileName }];

  const duration = result.audioDurationSec ?? source.durationSec;
  if (duration !== null) meta.push({ label: 'Duration', value: formatTimestamp(duration) });

  meta.push({ label: 'Transcribed', value: formatDate(doc.createdAt) });
  // An original whose language isn't known has no Language line, and its translation doesn't say what from.
  const from = original ? ` from ${original}` : '';
  if (translation) {
    meta.push({
      label: 'Language',
      value: `English (translated${from} with ${PROVIDER_NAMES[translation.provider]}, ${translation.model})`,
    });
  } else if (original) {
    meta.push({
      label: 'Language',
      value: request.languageHint === 'auto' ? `${original} (detected)` : original,
    });
  }
  meta.push({ label: 'Speakers', value: doc.speakers.map((s) => s.label).join(', ') });

  const terms = request.keyterms.length;
  const glossary = terms > 0 ? ` · glossary of ${terms} ${terms === 1 ? 'term' : 'terms'}` : '';
  meta.push({
    label: 'Transcription',
    value: `${TRANSCRIPTION_PROVIDER_NAMES[request.provider]} ${request.model}${glossary}`,
  });
  meta.push({ label: 'Exported', value: formatDate(opts.generatedAt.toISOString()) });

  const labels = new Map(doc.speakers.map((s) => [s.id, s.label]));
  const paragraphs = doc.turns.map((turn) => {
    const text = translation ? translation.texts[turn.id] : turn.text;
    if (text === undefined) throw new Error('translation incomplete');
    return {
      timestamp: formatTimestamp(turn.start),
      speaker: labels.get(turn.speakerId) ?? turn.speakerId,
      text,
    };
  });

  const title = `Transcript – ${fileBaseName(source.fileName)}`;
  return {
    title,
    meta,
    paragraphs,
    properties: { title, description: `Generated by DeScribe v${opts.appVersion}` },
  };
}

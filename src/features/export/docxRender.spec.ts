// @vitest-environment node
import JSZip from 'jszip';
import { describe, expect, it } from 'vitest';
import type { DocModel } from './docxModel';
import { renderDocx, xmlSafe } from './docxRender';

const MODEL: DocModel = {
  title: 'Transcript – interview',
  meta: [
    { label: 'Source file', value: 'interview.mp3' },
    { label: 'Speakers', value: 'Interviewer, Speaker 2' },
  ],
  paragraphs: [
    { timestamp: '00:00:00', speaker: 'Interviewer', text: 'Guten Tag und willkommen.' },
    { timestamp: '00:00:03', speaker: 'Speaker 2', text: 'Danke, ich freue mich sehr.' },
    { timestamp: '01:02:05', speaker: 'Interviewer', text: 'Was war die größte Herausforderung?' },
  ],
  properties: { title: 'Transcript – interview', description: 'Generated by DeScribe v1.2.3' },
};

async function unzip(model: DocModel) {
  const blob = await renderDocx(model);
  const zip = await JSZip.loadAsync(await blob.arrayBuffer());
  const read = (path: string) => zip.file(path)!.async('string');
  return {
    document: await read('word/document.xml'),
    styles: await read('word/styles.xml'),
    core: await read('docProps/core.xml'),
  };
}

/** The XML of each `<w:p>` paragraph, in order. */
const paragraphsOf = (xml: string) => xml.match(/<w:p>[\s\S]*?<\/w:p>|<w:p [\s\S]*?<\/w:p>/g) ?? [];
/** The XML of the run whose text is exactly `text`. */
const runWithText = (xml: string, text: string) =>
  (xml.match(/<w:r>[\s\S]*?<\/w:r>/g) ?? []).find((r) => r.includes(`>${text}</w:t>`));

describe('renderDocx', () => {
  it('writes the title, the details and one paragraph per turn', async () => {
    const { document } = await unzip(MODEL);
    const paragraphs = paragraphsOf(document);
    expect(paragraphs).toHaveLength(1 + MODEL.meta.length + MODEL.paragraphs.length);

    expect(paragraphs[0]).toContain('<w:pStyle w:val="Heading1"/>');
    expect(paragraphs[0]).toContain('Transcript – interview');

    for (const p of MODEL.paragraphs) {
      expect(document).toContain(`[${p.timestamp}] `);
      expect(document).toContain(`${p.speaker}: `);
      expect(document).toContain(p.text);
    }
  });

  it('makes speaker names and detail labels bold, and timestamps grey', async () => {
    const { document } = await unzip(MODEL);
    expect(runWithText(document, 'Interviewer: ')).toContain('<w:b/>');
    expect(runWithText(document, 'Source file: ')).toContain('<w:b/>');

    const timestamp = runWithText(document, '[00:00:03] ');
    expect(timestamp).toContain('<w:color w:val="666666"/>');
    expect(timestamp).not.toContain('<w:b/>');
    expect(runWithText(document, 'Danke, ich freue mich sehr.')).not.toContain('<w:b/>');
  });

  it('rules off the details and spaces the turns', async () => {
    const paragraphs = paragraphsOf((await unzip(MODEL)).document);
    const lastMeta = paragraphs[MODEL.meta.length]!;
    expect(lastMeta).toContain('Speakers: ');
    expect(lastMeta).toMatch(/<w:bottom w:val="single"/);
    expect(paragraphs[1]).not.toContain('<w:bottom');
    expect(paragraphs.at(-1)).toContain('<w:spacing w:after="120"/>');
  });

  it('sets Calibri 11 pt as the default font', async () => {
    const { styles } = await unzip(MODEL);
    const defaults = styles.match(/<w:docDefaults>[\s\S]*?<\/w:docDefaults>/)?.[0] ?? '';
    expect(defaults).toMatch(/<w:rFonts [^>]*w:ascii="Calibri"/);
    expect(defaults).toContain('<w:sz w:val="22"/>');
  });

  it('fills in the document properties', async () => {
    const { core } = await unzip(MODEL);
    expect(core).toContain('<dc:title>Transcript – interview</dc:title>');
    expect(core).toContain('<dc:creator>DeScribe</dc:creator>');
    expect(core).toContain('<dc:description>Generated by DeScribe v1.2.3</dc:description>');
  });

  it('drops characters that XML does not allow', async () => {
    const { document } = await unzip({
      ...MODEL,
      paragraphs: [{ timestamp: '00:00:00', speaker: 'A\u0007', text: 'Bad\u0000 text\ud800.' }],
    });
    expect(document).toContain('>A: </w:t>');
    expect(document).toContain('>Bad text.</w:t>');
  });
});

describe('xmlSafe', () => {
  it('keeps text, tabs, line breaks and emoji', () => {
    expect(xmlSafe('Grüße\tà\n😀 – ok')).toBe('Grüße\tà\n😀 – ok');
  });

  it('removes control characters, noncharacters and unpaired surrogates', () => {
    expect(xmlSafe('a\u0000b\u001fc\ufffed\uffffe\ud83df\ude00g')).toBe('abcdefg');
  });
});

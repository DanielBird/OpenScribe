import { createPinia, setActivePinia } from 'pinia';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import type { DocModel } from '../features/export/docxModel';
import { renderDocx } from '../features/export/docxRender';
import { downloadBlob } from '../features/export/download';
import { makeDoc, withTranslation } from '../testing/transcriptDoc';
import { EXPORT_ERROR, useExportStore } from './export';
import { useTranscriptStore } from './transcript';

vi.mock('../storage/idb', () => ({
  saveLastTranscript: vi.fn(() => Promise.resolve(true)),
  loadLastTranscript: vi.fn(() => Promise.resolve(null)),
}));
vi.mock('../features/export/docxRender', () => ({ renderDocx: vi.fn() }));
vi.mock('../features/export/download', () => ({ downloadBlob: vi.fn() }));

const render = vi.mocked(renderDocx);
const download = vi.mocked(downloadBlob);
const BLOB = new Blob(['docx']);

/** A render that waits until `finish()` or `fail()` is called. */
function heldRender() {
  let finish!: () => void;
  let fail!: (e: Error) => void;
  render.mockImplementationOnce(
    () =>
      new Promise<Blob>((resolve, reject) => {
        finish = () => resolve(BLOB);
        fail = reject;
      }),
  );
  return { finish: () => finish(), fail: (e: Error) => fail(e) };
}

describe('export store', () => {
  beforeEach(() => {
    setActivePinia(createPinia());
    render.mockReset().mockResolvedValue(BLOB);
    download.mockReset();
  });

  afterEach(() => {
    useTranscriptStore().$dispose();
    vi.restoreAllMocks();
  });

  const renderedModel = (): DocModel => render.mock.calls.at(-1)![0];

  it('renders the original and downloads it under its file name', async () => {
    await useTranscriptStore().setDoc(makeDoc());
    const store = useExportStore();
    await store.download('original');

    expect(renderedModel().title).toBe('Transcript – interview');
    expect(renderedModel().properties.description).toBe(
      `Generated by DeScribe v${__APP_VERSION__}`,
    );
    expect(download).toHaveBeenCalledExactlyOnceWith(BLOB, 'interview - transcript (German).docx');
    expect(store.busy).toBe(false);
    expect(store.error).toBeNull();
  });

  it('uses the current speaker names', async () => {
    const transcript = useTranscriptStore();
    await transcript.setDoc(makeDoc());
    transcript.renameSpeaker('speaker_0', 'Interviewer');
    await useExportStore().download('original');
    expect(renderedModel().paragraphs[0]?.speaker).toBe('Interviewer');
  });

  it('downloads the English version', async () => {
    await useTranscriptStore().setDoc(withTranslation(makeDoc()));
    const store = useExportStore();
    expect(store.hasTranslation).toBe(true);
    await store.download('en');
    expect(renderedModel().paragraphs[0]?.text).toBe(
      'Good afternoon and welcome to our conversation.',
    );
    expect(download).toHaveBeenCalledWith(BLOB, 'interview - transcript (English).docx');
  });

  it('is busy while rendering and ignores clicks meanwhile', async () => {
    await useTranscriptStore().setDoc(makeDoc());
    const store = useExportStore();
    const held = heldRender();

    const first = store.download('original');
    expect(store.busy).toBe(true);
    await store.download('original');
    expect(render).toHaveBeenCalledTimes(1);

    held.finish();
    await first;
    expect(store.busy).toBe(false);
    expect(download).toHaveBeenCalledTimes(1);
  });

  it('shows an error when the file cannot be built, and clears it on the next try', async () => {
    const consoleError = vi.spyOn(console, 'error').mockImplementation(() => {});
    await useTranscriptStore().setDoc(makeDoc());
    const store = useExportStore();
    const held = heldRender();

    const attempt = store.download('original');
    held.fail(new Error('zip failed'));
    await attempt;
    expect(store.error).toBe(EXPORT_ERROR);
    expect(store.busy).toBe(false);
    expect(download).not.toHaveBeenCalled();
    expect(consoleError).toHaveBeenCalledOnce();

    const retry = store.download('original');
    expect(store.error).toBeNull();
    await retry;
    expect(download).toHaveBeenCalledOnce();
  });

  it('reports an incomplete translation as an error', async () => {
    vi.spyOn(console, 'error').mockImplementation(() => {});
    await useTranscriptStore().setDoc(withTranslation(makeDoc(), { t1: 'Hello.' }));
    const store = useExportStore();
    await store.download('en');
    expect(store.error).toBe(EXPORT_ERROR);
    expect(render).not.toHaveBeenCalled();
  });

  it('clears the error when another transcript is shown', async () => {
    vi.spyOn(console, 'error').mockImplementation(() => {});
    const transcript = useTranscriptStore();
    await transcript.setDoc(makeDoc());
    const store = useExportStore();
    render.mockRejectedValueOnce(new Error('zip failed'));
    await store.download('original');
    expect(store.error).toBe(EXPORT_ERROR);

    transcript.renameSpeaker('speaker_0', 'Interviewer');
    await Promise.resolve();
    expect(store.error).toBe(EXPORT_ERROR); // same transcript

    await transcript.setDoc(makeDoc({ id: 'another-doc' }));
    await Promise.resolve();
    expect(store.error).toBeNull();
  });

  it('does nothing without a transcript', async () => {
    const store = useExportStore();
    expect(store.hasTranslation).toBe(false);
    await store.download('original');
    expect(render).not.toHaveBeenCalled();
    expect(download).not.toHaveBeenCalled();
  });
});
